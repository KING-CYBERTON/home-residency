// Generates the typed API surface from the backend contract:
//   src/api/schema.d.ts  request/response types (openapi-typescript)
//   src/api/roles.gen.ts which staff roles may call each operation (x-roles)
//   src/api/enums.gen.ts runtime lists of the contract's string enums
// The backend enforces x-roles itself; the console reads the same list so it
// only offers actions the signed-in user is allowed to take.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const spec = resolve(root, "../backend/api/openapi.yaml");

execFileSync(resolve(root, "node_modules/.bin/openapi-typescript"), [spec, "-o", resolve(root, "src/api/schema.d.ts")], {
  stdio: "inherit",
});

const doc = parse(readFileSync(spec, "utf8"));
const methods = ["get", "post", "put", "patch", "delete"];
const lines = [];
const info = [];
for (const [path, item] of Object.entries(doc.paths)) {
  for (const method of methods) {
    const op = item[method];
    if (!op || !op["x-roles"]) continue;
    const key = JSON.stringify(`${method.toUpperCase()} ${path}`);
    lines.push(`  ${key}: ${JSON.stringify(op["x-roles"])},`);
    info.push(`  ${key}: ${JSON.stringify({ summary: op.summary ?? "", area: op.tags?.[0] ?? "" })},`);
  }
}
writeFileSync(
  resolve(root, "src/api/roles.gen.ts"),
  `// Code generated by scripts/gen-api.mjs from backend/api/openapi.yaml. DO NOT EDIT.\n` +
    `// "any staff" means every staff role; "(read)" entries are informational.\n\n` +
    `export const operationRoles: Record<string, readonly string[]> = {\n${lines.join("\n")}\n};\n\n` +
    `/** What each operation does, for the Roles page. */\n` +
    `export const operationInfo: Record<string, { summary: string; area: string }> = {\n${info.join("\n")}\n};\n`,
);
console.log(`roles.gen.ts: ${lines.length} operations`);

// Runtime lists of every string enum, for filters and form selects.
const enums = Object.entries(doc.components.schemas)
  .filter(([, s]) => s.type === "string" && Array.isArray(s.enum))
  .map(([name, s]) => `export const ${name} = ${JSON.stringify(s.enum)} as const;`);
writeFileSync(
  resolve(root, "src/api/enums.gen.ts"),
  `// Code generated by scripts/gen-api.mjs from backend/api/openapi.yaml. DO NOT EDIT.\n\n${enums.join("\n")}\n`,
);
console.log(`enums.gen.ts: ${enums.length} enums`);
